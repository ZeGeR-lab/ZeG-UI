"""Compile Lua sources and run simulated-client checks. Does not launch WoW."""
import ctypes
import ctypes.util
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
lib = ctypes.util.find_library("lua5.4") or ctypes.util.find_library("lua5.3")
if not lib:
    raise SystemExit("Install a Lua 5.3/5.4 shared library to run the development checks.")
lua = ctypes.CDLL(lib)
lua.luaL_newstate.restype = ctypes.c_void_p
lua.luaL_openlibs.argtypes = [ctypes.c_void_p]
lua.luaL_loadfilex.argtypes = [ctypes.c_void_p, ctypes.c_char_p, ctypes.c_char_p]
lua.luaL_loadstring.argtypes = [ctypes.c_void_p, ctypes.c_char_p]
lua.lua_pcallk.argtypes = [ctypes.c_void_p, ctypes.c_int, ctypes.c_int, ctypes.c_int, ctypes.c_longlong, ctypes.c_void_p]
lua.lua_tolstring.argtypes = [ctypes.c_void_p, ctypes.c_int, ctypes.c_void_p]
lua.lua_tolstring.restype = ctypes.c_char_p
lua.lua_settop.argtypes = [ctypes.c_void_p, ctypes.c_int]
lua.lua_close.argtypes = [ctypes.c_void_p]

def check(state, status):
    if status:
        message = lua.lua_tolstring(state, -1, None)
        raise AssertionError(message.decode() if message else "Lua error")

state = lua.luaL_newstate()
try:
    for path in root.glob("*.lua"):
        check(state, lua.luaL_loadfilex(state, str(path).encode(), None))
        lua.lua_settop(state, 0)
        print(f"Syntax OK: {path.name}")
finally:
    lua.lua_close(state)

modes = ("normal", "combat_parent_shift", "combat_parent_shift_scaled", "combat_parent_shift_triangles", "combat_parent_shift_triangles_scaled", "disabled", "unsupported", "modules_off", "missing_optional", "utility_only", "xp_off", "menu_off", "cast_off", "migration", "appearance_migration", "preset_layout", "gamepad_active", "missing_native_api", "full_profiles", "druid_forms", "no_forms", "utility_modes", "bag_fallback", "menu_scaled", "cast_fill_masked", "cast_fill_masked_scaled", "xp_late_refresh", "xp_late_refresh_scaled")
modes += ("minimap_scaled", "minimap_legacy_icons", "minimap_no_icons", "minimap_missing_api", "minimap_migration", "party_offline", "cooldown_numbers")
modes += ("vehicle_exit", "vehicle_exit_scaled")
modes += ("custom_profiles", "custom_profile_validation", "custom_profile_combat", "custom_alignment",
          "custom_bars", "custom_bars_combat", "custom_fonts", "custom_themes", "custom_auras",
          "custom_tooltips", "custom_swing", "custom_fading", "custom_ui")
modes += ("meters_native", "meters_colors", "meters_secret", "meters_restore", "meters_combat", "meters_profiles",
          "meters_ui", "meters_late", "meters_missing", "meters_off", "meters_forbidden")
modes += ("custom_aura_sizes", "custom_aura_sizes_scaled")
modes += ("trackers_native", "custom_patterns")
selected = sys.argv[1:] or modes
if set(selected) - set(modes):
    raise SystemExit("Unknown simulated scenario: " + ", ".join(sorted(set(selected) - set(modes))))
for mode in selected:
    state = lua.luaL_newstate()
    try:
        lua.luaL_openlibs(state)
        # The paths are generated by Python; Lua long strings avoid shell/string escaping.
        setup = f"ADDON_ROOT = [[{root}]]; TEST_MODE = [[{mode}]]"
        check(state, lua.luaL_loadstring(state, setup.encode()))
        check(state, lua.lua_pcallk(state, 0, 0, 0, 0, None))
        check(state, lua.luaL_loadfilex(state, str(root / "tests/runtime_smoke.lua").encode(), None))
        check(state, lua.lua_pcallk(state, 0, 0, 0, 0, None))
        print(f"Runtime OK: {mode}")
    finally:
        lua.lua_close(state)
print("All simulated checks passed. Live-client visual and secure-click testing is still required.")
